// Глобальное состояние курсора
static int  s_cur_x       = 0;
static int  s_cur_y       = 0;
static int  s_cur_prev_x  = 0;  // позиция ДО последнего move
static int  s_cur_prev_y  = 0;
static bool s_cur_visible = false;
static bool s_cur_locked  = false;

// Рисует курсор напрямую в VRAM (вызывается из gfx_flip)
static void cursor_blit_vram(int x, int y) {
    for (int dy = 0; dy < GFX_CURSOR_H; dy++) {
        for (int dx = 0; dx < GFX_CURSOR_W; dx++) {
            uint8_t t = CURSOR_ARROW[dy][dx];
            if (t == 0) continue;
            uint8_t color = (t == 1) ? GFX_WHITE : GFX_BLACK;
            int px = x + dx, py = y + dy;
            if (px < 0 || px >= gfx_width || py < 0 || py >= gfx_height) continue;
            if (lfb_ready && lfb_bpp == 32) {
                ((uint32_t*)lfb_addr)[(uint32_t)py*(lfb_pitch/4)+(uint32_t)px]
                    = vga_palette_32[color];
            } else if (lfb_ready && lfb_bpp == 24) {
                uint8_t* fb  = (uint8_t*)lfb_addr;
                uint32_t c   = vga_palette_32[color];
                uint32_t off = (uint32_t)py * lfb_pitch + (uint32_t)px * 3;
                fb[off+0] = (uint8_t)(c & 0xFF);
                fb[off+1] = (uint8_t)((c >> 8)  & 0xFF);
                fb[off+2] = (uint8_t)((c >> 16) & 0xFF);
            } else if (gfx_mode_active && !gfx_mode_x) {
                VRAM[(uint32_t)py*(uint32_t)gfx_width+(uint32_t)px] = color;
            } else if (gfx_mode_active && gfx_mode_x) {
                outb(0x3C4, 0x02);
                outb(0x3C5, (uint8_t)(1 << (px & 3)));
                VRAM[(uint32_t)py*((uint32_t)gfx_width/4)+(uint32_t)(px/4)] = color;
            }
        }
    }
}

// Рисует курсор МЫШИ прямо в backbuffer (индексами 0/15 = чёрный/белый),
// а не поверх VRAM. Нужно, чтобы курсор переносился в VRAM вместе со сценой
// при gfx_flip() и НЕ мерцал: при рисовании поверх VRAM он стёрт копированием
// бо́льшую часть кадра. Клиппинг на время рисования отключаем (иначе курсор
// обрежется, если активен gfx_set_clip), потом восстанавливаем.
void gfx_cursor_blit_backbuffer(int x, int y) {
    bool clip_saved = s_clip_active;
    s_clip_active = false;
    for (int dy = 0; dy < GFX_CURSOR_H; dy++)
        for (int dx = 0; dx < GFX_CURSOR_W; dx++) {
            uint8_t t = CURSOR_ARROW[dy][dx];
            if (t == 0) continue;
            gfx_put_pixel(x + dx, y + dy, (t == 1) ? GFX_WHITE : GFX_BLACK);
        }
    s_clip_active = clip_saved;
}

// Записать один пиксель из backbuffer → VRAM (восстановление фона под курсором)
static void vram_put_from_backbuf(int px, int py) {
    if (px < 0 || px >= gfx_width || py < 0 || py >= gfx_height) return;
    uint8_t idx = backbuffer[(uint32_t)py * (uint32_t)gfx_width + (uint32_t)px];
    if (lfb_ready && lfb_bpp == 32) {
        ((uint32_t*)lfb_addr)[(uint32_t)py*(lfb_pitch/4)+(uint32_t)px]
            = vga_palette_32[idx];
    } else if (lfb_ready && lfb_bpp == 24) {
        uint8_t* fb  = (uint8_t*)lfb_addr;
        uint32_t c   = vga_palette_32[idx];
        uint32_t off = (uint32_t)py * lfb_pitch + (uint32_t)px * 3;
        fb[off+0] = (uint8_t)(c & 0xFF);
        fb[off+1] = (uint8_t)((c >> 8)  & 0xFF);
        fb[off+2] = (uint8_t)((c >> 16) & 0xFF);
    } else if (gfx_mode_active && !gfx_mode_x) {
        VRAM[(uint32_t)py * (uint32_t)gfx_width + (uint32_t)px] = idx;
    }
}

void gfx_cursor_show()             { s_cur_visible = true;  }
void gfx_cursor_hide()             { s_cur_visible = false; }
void gfx_cursor_set_locked(bool l) { s_cur_locked  = l;    }
void gfx_cursor_move(int x, int y) {
    if (s_cur_locked) return;
    if (x < 0) x = 0; if (x >= gfx_width)  x = gfx_width  - 1;
    if (y < 0) y = 0; if (y >= gfx_height) y = gfx_height - 1;
    s_cur_prev_x = s_cur_x;   // запоминаем старую позицию
    s_cur_prev_y = s_cur_y;
    s_cur_x = x; s_cur_y = y;
}
int gfx_cursor_get_x() { return s_cur_x; }
int gfx_cursor_get_y() { return s_cur_y; }

// Быстрое обновление курсора БЕЗ полного flip:
//   1. Восстанавливает пиксели под старым курсором из backbuffer → VRAM
//   2. Рисует курсор на новой позиции в VRAM
// Вызывать только когда сцена не изменилась, двинулся лишь курсор.
void gfx_cursor_update_pos() {
    if (!s_cur_visible) return;
    // Восстанавливаем старую позицию из backbuffer
    for (int dy = 0; dy < GFX_CURSOR_H; dy++)
        for (int dx = 0; dx < GFX_CURSOR_W; dx++)
            vram_put_from_backbuf(s_cur_prev_x + dx, s_cur_prev_y + dy);
    // Рисуем курсор на новой позиции
    cursor_blit_vram(s_cur_x, s_cur_y);
}

void gfx_cursor_save   (int, int) {}
void gfx_cursor_restore(int, int) {}
void gfx_cursor_draw   (int x, int y) { cursor_blit_vram(x, y); }

// ─── Двойная буферизация: perенос backbuffer → VRAM ──────────────────────────
void gfx_flip() {
    if (lfb_ready) {
        if (lfb_bpp == 32) {
            uint32_t* fb     = (uint32_t*)lfb_addr;
            uint32_t  stride = lfb_pitch / 4;
            for (int y = 0; y < gfx_height; y++) {
                uint32_t*       dst = fb + (uint32_t)y * stride;
                const uint8_t*  src = backbuffer + (uint32_t)y * (uint32_t)gfx_width;
                for (int x = 0; x < gfx_width; x++)
                    dst[x] = vga_palette_32[src[x]];
            }
        } else if (lfb_bpp == 24) {
            uint8_t* fb = (uint8_t*)lfb_addr;
            for (int y = 0; y < gfx_height; y++) {
                uint8_t*       dst = fb + (uint32_t)y * lfb_pitch;
                const uint8_t* src = backbuffer + (uint32_t)y * (uint32_t)gfx_width;
                for (int x = 0; x < gfx_width; x++) {
                    uint32_t c = vga_palette_32[src[x]];
                    dst[x*3+0] = (uint8_t)(c & 0xFF);
                    dst[x*3+1] = (uint8_t)((c >> 8)  & 0xFF);
                    dst[x*3+2] = (uint8_t)((c >> 16) & 0xFF);
                }
            }
        }
    } else if (gfx_mode_active) {
        if (!gfx_mode_x) {
            // Mode 13h: прямое копирование
            uint32_t total = (uint32_t)gfx_width * (uint32_t)gfx_height;
            for (uint32_t i = 0; i < total; i++) VRAM[i] = backbuffer[i];
        } else {
            // Mode X: по плоскостям
            outb(0x3C4, 0x02);
            for (int y = 0; y < gfx_height; y++)
                for (int x = 0; x < gfx_width; x++) {
                    uint32_t addr = (uint32_t)y * ((uint32_t)gfx_width / 4) + (uint32_t)(x / 4);
                    outb(0x3C5, (uint8_t)(1 << (x & 3)));
                    VRAM[addr] = backbuffer[(uint32_t)y * (uint32_t)gfx_width + (uint32_t)x];
                }
            outb(0x3C5, 0x0F);
        }
    }
    // Курсор рисуется ПОВЕРХ VRAM — всегда последним, не мигает
    if (s_cur_visible) cursor_blit_vram(s_cur_x, s_cur_y);
}