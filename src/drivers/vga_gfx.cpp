// Переключение банка для режимов > 64KB (640x480)
// Один банк = 64KB. Для 640x480x1 нужно 300KB = 5 банков.
static void vga_set_bank(int bank) {
    if (bank == gfx_current_bank) return;
    gfx_current_bank = bank;
    // Порты 0x3CD (некоторые карты) или через Sequencer/GC
    // Стандартный способ через GC регистр 6 и Sequencer:
    outb(0x3C4, 0x04); outb(0x3C5, 0x06);    // chain-4 off
    // Window A: порт 0x3CE/0x3CF регистр 9 (SVGA) — но проще через BIOS
    // Используем стандартный VGA способ: пишем в GC регистр Write Bank
    // На VGA/SVGA банк переключается через расширенные регистры (chip-specific).
    // Для совместимости с QEMU используем прямую запись через GC:
    outb(0x3CE, 0x09); outb(0x3CF, (uint8_t)(bank & 0xFF));
    outb(0x3CE, 0x0A); outb(0x3CF, (uint8_t)(bank & 0xFF));
}

