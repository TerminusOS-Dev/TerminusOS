// ─── Регистры VGA для режима 640x480x256 (mode Y / unchained) ────────────────
// Это "Mode X"-подобный режим без chain-4, с 256 цветами.
// Используется linear addressing через plane switching.
// VRAM: 640*480 = 307200 байт, разбито по 4 planes.
// Пиксель (x,y): plane = x & 3, адрес = (y*160 + x/4) в plane
// Один банк 64KB * 4 planes = 256KB → вмещает весь экран.
static void vga_write_regs_mode_640x480() {
    // Misc Output
    outb(0x3C2, 0xE3);

    // Sequencer
    outb(0x3C4, 0x00); outb(0x3C5, 0x03); // Reset
    outb(0x3C4, 0x01); outb(0x3C5, 0x01); // Clocking Mode
    outb(0x3C4, 0x02); outb(0x3C5, 0x0F); // Map Mask: все 4 плейна
    outb(0x3C4, 0x03); outb(0x3C5, 0x00); // Character Map
    outb(0x3C4, 0x04); outb(0x3C5, 0x06); // Memory Mode: chain-4 off, extended

    // Снимаем защиту CRTC
    outb(0x3D4, 0x11); outb(0x3D5, inb(0x3D5) & 0x7F);

    // CRTC для 640x480 (31.5kHz горизонт, 60Гц вертикаль)
    static const uint8_t crtc[] = {
        0x5F, // 00: Horiz Total
        0x4F, // 01: Horiz Display End
        0x50, // 02: Start Horiz Blank
        0x82, // 03: End Horiz Blank
        0x54, // 04: Start Horiz Retrace
        0x80, // 05: End Horiz Retrace
        0x0B, // 06: Vertical Total
        0x3E, // 07: Overflow
        0x00, // 08: Preset Row Scan
        0x40, // 09: Max Scan Line (без doubling)
        0x00, // 0A: Cursor Start
        0x00, // 0B: Cursor End
        0x00, // 0C: Start Address High
        0x00, // 0D: Start Address Low
        0x00, // 0E: Cursor High
        0x00, // 0F: Cursor Low
        0xEA, // 10: Vertical Retrace Start
        0x8C, // 11: Vertical Retrace End
        0xDF, // 12: Vertical Display End
        0xA0, // 13: Offset (640/4 = 160 = 0xA0)
        0x00, // 14: Underline Location
        0xE7, // 15: Start Vertical Blank
        0x04, // 16: End Vertical Blank
        0xE3, // 17: Mode Control (byte mode, не word)
        0xFF, // 18: Line Compare
    };
    for (int i = 0; i < 25; i++) { outb(0x3D4, i); outb(0x3D5, crtc[i]); }

    // Graphics Controller
    outb(0x3CE, 0x00); outb(0x3CF, 0x00); // Set/Reset
    outb(0x3CE, 0x01); outb(0x3CF, 0x00); // Enable Set/Reset
    outb(0x3CE, 0x02); outb(0x3CF, 0x00); // Color Compare
    outb(0x3CE, 0x03); outb(0x3CF, 0x00); // Data Rotate
    outb(0x3CE, 0x04); outb(0x3CF, 0x00); // Read Map Select
    outb(0x3CE, 0x05); outb(0x3CF, 0x00); // Mode: write mode 0 (нужен для прямой записи в plane)
    outb(0x3CE, 0x06); outb(0x3CF, 0x05); // Misc: не odd/even, map at A000
    outb(0x3CE, 0x07); outb(0x3CF, 0x0F); // Color Don't Care
    outb(0x3CE, 0x08); outb(0x3CF, 0xFF); // Bit Mask

    // Attribute Controller
    inb(0x3DA);
    static const uint8_t ac[] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0A,0x0B,0x0C,0x0D,0x0E,0x0F,
        0x41, // 10: Mode Control (графика)
        0x00, // 11: Overscan
        0x0F, // 12: Color Plane Enable
        0x00, // 13: Horiz Pixel Panning
        0x00, // 14: Color Select
    };
    for (int i = 0; i < 21; i++) { outb(0x3C0, i); outb(0x3C0, ac[i]); }
    outb(0x3C0, 0x20); // включить дисплей
}

// ─── Переключение режимов ─────────────────────────────────────────────────────
void vga_enter_mode13() {
    serial_write("[GFX] enter_mode13 start, lfb_ready=");
    serial_hex8((uint8_t)lfb_ready);
    serial_write("\n");
    if (lfb_ready) {
        gfx_width  = (int)lfb_width;
        gfx_height = (int)lfb_height;
        gfx_banked = false; gfx_current_bank = -1;
        gfx_mode_x = false;
        gfx_mode_active = true;
        vbe_enable(lfb_width, lfb_height, lfb_bpp);  // QEMU: включить VBE обратно
        gfx_init_palette();
        gfx_clear(GFX_BLACK);
        gfx_flip();   // синхронизируем VRAM с backbuffer
        return;
    }
    vga_write_regs_mode13();
    serial_write("[GFX] enter_mode13: regs done\n");
    gfx_width = 320; gfx_height = 200;
    gfx_banked = false; gfx_current_bank = -1;
    gfx_mode_x = false;
    gfx_mode_active = true;
    gfx_init_palette();
    serial_write("[GFX] enter_mode13: palette done\n");
    gfx_clear(GFX_BLACK);
    gfx_flip();   // синхронизируем VRAM с backbuffer
    serial_write("[GFX] enter_mode13: clear done\n");
}

void vga_enter_mode_640x480() {
    serial_write("[GFX] enter_mode640 start, lfb_ready=");
    serial_hex8((uint8_t)lfb_ready);
    serial_write("\n");
    // Если GRUB дал нам LFB — используем его (настоящий 640x480)
    if (lfb_ready) {
        gfx_width  = (int)lfb_width;
        gfx_height = (int)lfb_height;
        gfx_banked = false;
        gfx_mode_x = false;
        gfx_mode_active = true;
        vbe_enable(lfb_width, lfb_height, lfb_bpp);  // QEMU: включить VBE обратно
        gfx_init_palette();
        gfx_clear(GFX_BLACK);
        gfx_flip();   // синхронизируем VRAM с backbuffer
        return;
    }
    // Fallback: Mode X через регистры (всё ещё 320x200 физически)
    vga_write_regs_mode_640x480();
    serial_write("[GFX] enter_mode640: regs done\n");
    gfx_width = 640; gfx_height = 480;
    gfx_banked = false; gfx_current_bank = -1;
    gfx_mode_x = true;
    gfx_mode_active = true;
    gfx_init_palette();
    serial_write("[GFX] enter_mode640: palette done\n");
    gfx_clear(GFX_BLACK);
    gfx_flip();   // синхронизируем VRAM с backbuffer
    serial_write("[GFX] enter_mode640: clear done\n");
}

