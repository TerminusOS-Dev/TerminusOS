// Записать шрифт в plane 2 видеопамяти текстового режима
static void vga_restore_font() {
    volatile uint8_t* vram = (volatile uint8_t*)0xA0000;

    // Включаем запись в plane 2
    outb(0x3C4, 0x02); outb(0x3C5, 0x04); // Map Mask: plane 2 only
    outb(0x3C4, 0x04); outb(0x3C5, 0x06); // Memory Mode: chain-4 off, odd/even off
    outb(0x3CE, 0x05); outb(0x3CF, 0x00); // Graphics Mode: write mode 0, read mode 0
    outb(0x3CE, 0x06); outb(0x3CF, 0x04); // Misc: не odd/even, map at A000

    // Каждый символ занимает 32 байта в plane 2 (пишем 16, остальные нули)
    for (int ch = 0; ch < 128; ch++) {
        for (int row = 0; row < 16; row++)
            vram[ch * 32 + row] = VGA_FONT_8x16[ch * 16 + row];
        for (int row = 16; row < 32; row++)
            vram[ch * 32 + row] = 0x00;
    }

    // Восстанавливаем нормальный режим работы памяти (текстовый odd/even)
    outb(0x3C4, 0x02); outb(0x3C5, 0x03); // Map Mask: plane 0 + 1
    outb(0x3C4, 0x04); outb(0x3C5, 0x02); // Memory Mode: odd/even on
    outb(0x3CE, 0x05); outb(0x3CF, 0x10); // Graphics Mode: odd/even read
    outb(0x3CE, 0x06); outb(0x3CF, 0x0E); // Misc: text map at B800, odd/even
}

void vga_exit_to_text() {
    if (lfb_ready) {
        uint32_t save_w = gfx_width, save_h = gfx_height;
        gfx_width  = (int)lfb_width;
        gfx_height = (int)lfb_height;
        gfx_clear(GFX_BLACK);
        gfx_flip();      // сначала чистим экран через LFB
        gfx_width  = save_w;
        gfx_height = save_h;
        vbe_disable();   // явно отключаем VBE — QEMU переходит на VGA B8000
    }
    vga_write_regs_mode3();
    vga_set_text_dac();
    vga_restore_font();
    gfx_mode_active = false;
}

// Вызывается при старте ядра: переключаем в текстовый режим
// (GRUB мог оставить железо в LFB/VESA-режиме)
void vga_init_text_mode() {
    // Очищаем LFB ДО изменения регистров (пока память ещё отображена на LFB)
    if (lfb_ready) {
        if (lfb_bpp == 32) {
            uint32_t* fb = (uint32_t*)lfb_addr;
            uint32_t total = (lfb_pitch / 4) * lfb_height;
            for (uint32_t i = 0; i < total; i++) fb[i] = 0x00000000;
        } else {
            uint8_t* fb = (uint8_t*)lfb_addr;
            uint32_t total = lfb_pitch * lfb_height;
            for (uint32_t i = 0; i < total; i++) fb[i] = 0;
        }
    }

    vbe_disable();
    vga_write_regs_mode3();
    vga_set_text_dac();
    vga_restore_font();
}

// ─── Палитра ──────────────────────────────────────────────────────────────────
void gfx_set_palette(uint8_t idx, uint8_t r, uint8_t g, uint8_t b) {
    outb(0x3C8, idx);
    outb(0x3C9, r);
    outb(0x3C9, g);
    outb(0x3C9, b);
    // LFB-рендер (gfx_flip) берёт цвет НЕ из DAC, а из vga_palette_32,
    // поэтому без этой синхронизации любое переназначение палитры невидимо.
    uint8_t r8 = (uint8_t)((r << 2) | (r >> 4));
    uint8_t g8 = (uint8_t)((g << 2) | (g >> 4));
    uint8_t b8 = (uint8_t)((b << 2) | (b >> 4));
    vga_palette_32[idx] = ((uint32_t)r8 << 16) | ((uint32_t)g8 << 8) | (uint32_t)b8;
}

void gfx_init_palette() {
    // Полная 256-цветная палитра (значения 0-63 для DAC)
    // 0-15: стандартные VGA
    static const uint8_t std16[16][3] = {
        {  0,  0,  0 }, // 0  Black
        {  0,  0, 42 }, // 1  Blue
        {  0, 42,  0 }, // 2  Green
        {  0, 42, 42 }, // 3  Cyan
        { 42,  0,  0 }, // 4  Red
        { 42,  0, 42 }, // 5  Magenta
        { 42, 21,  0 }, // 6  Brown
        { 42, 42, 42 }, // 7  Light Gray
        { 21, 21, 21 }, // 8  Dark Gray
        { 21, 21, 63 }, // 9  Light Blue
        { 21, 63, 21 }, // 10 Light Green
        { 21, 63, 63 }, // 11 Light Cyan
        { 63, 21, 21 }, // 12 Light Red
        { 63, 21, 63 }, // 13 Light Magenta
        { 63, 63, 21 }, // 14 Yellow
        { 63, 63, 63 }, // 15 White
    };
    for (int i = 0; i < 16; i++)
        gfx_set_palette((uint8_t)i, std16[i][0], std16[i][1], std16[i][2]);

    // 16-31: градации серого
    for (int i = 0; i < 16; i++) {
        uint8_t v = (uint8_t)(i * 4); // 0..60
        gfx_set_palette((uint8_t)(16 + i), v, v, v);
    }

    // 32-247: куб 6×6×6 RGB (216 цветов) — типичная VGA 256-color раскладка
    static const uint8_t levels[6] = { 0, 12, 25, 38, 51, 63 };
    int idx = 32;
    for (int r = 0; r < 6; r++)
        for (int g = 0; g < 6; g++)
            for (int b = 0; b < 6; b++) {
                gfx_set_palette((uint8_t)idx,
                                levels[r], levels[g], levels[b]);
                idx++;
            }

    // 248-255: дополнительные оттенки серого
    for (int i = 0; i < 8; i++) {
        uint8_t v = (uint8_t)(7 + i * 8);
        if (v > 63) v = 63;
        gfx_set_palette((uint8_t)(248 + i), v, v, v);
    }
}

// ─── Программный клиппинг (API) ──────────────────────────────────────────────
void gfx_set_clip(int x, int y, int w, int h) {
    s_clip_x1 = x;     s_clip_y1 = y;
    s_clip_x2 = x + w; s_clip_y2 = y + h;
    s_clip_active = true;
}
void gfx_clear_clip() { s_clip_active = false; }

// ─── Примитивы рисования ─────────────────────────────────────────────────────
// Всё пишем в backbuffer. gfx_flip() переносит в VRAM.
void gfx_put_pixel(int x, int y, uint8_t color) {
    if (x < 0 || x >= gfx_width || y < 0 || y >= gfx_height) return;
    if (s_clip_active && (x < s_clip_x1 || x >= s_clip_x2 ||
                          y < s_clip_y1 || y >= s_clip_y2)) return;
    backbuffer[(uint32_t)y * (uint32_t)gfx_width + (uint32_t)x] = color;
}

void gfx_clear(uint8_t color) {
    uint32_t total = (uint32_t)gfx_width * (uint32_t)gfx_height;
    for (uint32_t i = 0; i < total; i++) backbuffer[i] = color;
}

uint8_t* gfx_get_backbuffer() { return backbuffer; }

void gfx_fill_rect(int x, int y, int w, int h, uint8_t color) {
    for (int row = y; row < y + h; row++)
        for (int col = x; col < x + w; col++)
            gfx_put_pixel(col, row, color);
}

void gfx_draw_hline(int x, int y, int len, uint8_t color) {
    for (int i = 0; i < len; i++) gfx_put_pixel(x + i, y, color);
}

void gfx_draw_vline(int x, int y, int len, uint8_t color) {
    for (int i = 0; i < len; i++) gfx_put_pixel(x, y + i, color);
}

void gfx_draw_rect(int x, int y, int w, int h, uint8_t color) {
    gfx_draw_hline(x, y,         w, color);
    gfx_draw_hline(x, y + h - 1, w, color);
    gfx_draw_vline(x,         y, h, color);
    gfx_draw_vline(x + w - 1, y, h, color);
}

void gfx_draw_line(int x0, int y0, int x1, int y1, uint8_t color) {
    // Алгоритм Брезенхема
    int dx =  (x1 > x0 ? x1 - x0 : x0 - x1);
    int dy = -(y1 > y0 ? y1 - y0 : y0 - y1);
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;
    while (true) {
        gfx_put_pixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

// ─── Вывод текста ─────────────────────────────────────────────────────────────
void gfx_draw_char(int x, int y, char c, uint8_t fg, uint8_t bg) {
    if (c < 32 || c > 127) c = '?';
    const uint8_t* glyph = FONT8x8[c - 32];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                gfx_put_pixel(x + col, y + row, fg);
            } else if (bg != GFX_TRANSPARENT) {
                gfx_put_pixel(x + col, y + row, bg);
            }
        }
    }
}

void gfx_draw_text(int x, int y, const char* str, uint8_t fg, uint8_t bg) {
    int cx = x;
    for (int i = 0; str[i]; i++) {
        if (str[i] == '\n') {
            cx = x;
            y += 9; // 8 пикселей шрифт + 1 межстрочный
        } else {
            gfx_draw_char(cx, y, str[i], fg, bg);
            cx += 8;
        }
    }
}

