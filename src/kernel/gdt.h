#ifndef GDT_H
#define GDT_H

#include <stdint.h>

// ─── Своя GDT в C++ ───────────────────────────────────────────────────────────
// Загрузчик (boot/stage2.asm) уже ставит плоскую GDT из 3 записей (null,
// код 0x08, данные 0x10) ещё в реальном режиме, до перехода в защищённый —
// и всё ядро с тех пор на ней и живёт. Здесь та же самая раскладка
// повторяется 1-в-1 (иначе всё, что уже работает, сломается), плюс
// добавляются пустые слоты 6-8 — конвенция Linux i386 для TLS
// (GDT_ENTRY_TLS_MIN..MAX), которые изначально пустые и заполняются позже
// через gdt_set_tls() из set_thread_area().

struct GdtEntry {
    uint16_t limit_low;
    uint16_t base_low;
    uint8_t  base_mid;
    uint8_t  access;
    uint8_t  granularity;
    uint8_t  base_high;
} __attribute__((packed));

struct GdtPtr {
    uint16_t limit;
    uint32_t base;
} __attribute__((packed));

// Ставит новую (расширенную) GDT — вызвать один раз при старте ядра, ДО
// первого использования TLS. Селекторы 0x08 (код) и 0x10 (данные) остаются
// ровно теми же, что уже были — существующий код это не заметит.
void gdt_init();

// Настраивает TLS-слот (индекс 6, 7 или 8) на базовый адрес base с плоским
// (4 ГБ, постранично) лимитом — именно так его обычно и просит musl.
// Возвращает селектор (с RPL=3 — см. комментарий в gdt.cpp, почему) или 0
// при неверном индексе.
uint16_t gdt_set_tls(int index, uint32_t base);

#endif
