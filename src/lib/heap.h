#ifndef HEAP_H
#define HEAP_H

#include <stdint.h>
#include <stddef.h>

// ─── Простой аллокатор кучи ──────────────────────────────────────────────────
// Пул — статический массив внутри BSS самого ядра (см. heap.cpp): никакой
// физической карты памяти не нужно, никакого риска пересечься с чем-то ещё —
// компилятор/линковщик гарантируют, что этот массив не пересекается ни с чем
// другим в образе ядра. Внутри — first-fit со сращиванием соседних свободных
// блоков при освобождении, и "канарейка" (магическое число) в заголовке
// каждого блока: kfree() на битом/чужом указателе паникует явно, а не тихо
// портит кучу дальше.

void  heap_init();
void* kmalloc(size_t size);
void  kfree(void* ptr);
void* krealloc(void* ptr, size_t new_size);

size_t heap_total();   // размер пула целиком, байт
size_t heap_used();    // сейчас занято, байт
size_t heap_free();    // сейчас свободно, байт (с учётом фрагментации — крупный
                        // кусок может не влезть даже если суммарно места хватает)

// Проходит по всему списку блоков и проверяет целостность (канарейки на
// месте, размеры сходятся с размером пула). true = всё в порядке.
// Дёшево вызывать после подозрительных операций, если параноишь.
bool heap_check();

// Стандартные имена — тонкие обёртки над kmalloc/kfree, для кода, который
// ожидает обычный C malloc/free (будущий перенос сторонних вещей).
extern "C" void* malloc(size_t size);
extern "C" void  free(void* ptr);
extern "C" void* realloc(void* ptr, size_t new_size);

#endif
